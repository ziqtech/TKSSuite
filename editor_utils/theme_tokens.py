def tokens_for(family: str, is_dark: bool) -> dict[str, str]:
    """返回指定族、指定深浅主题的 槽位名 -> 字面值 映射。"""
    slots = _FAMILY_SLOTS[family]
    idx = 0 if is_dark else 1
    return {name: pair[idx] for name, pair in slots.items()}


